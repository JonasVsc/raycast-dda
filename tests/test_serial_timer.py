TOTAL_RAY_COUNT = 400
RAYS_PER_CHUNK  = 400

TEST_SCENARIOS = [
    ("scenario_1", 1.4, 1.4, -1.0, 0.0, 0.0, 1.0),
    ("scenario_16", 1.1, 1.1, 0.7071, 0.7071, -0.4667, 0.4667)
]

def bitpack_map(map_data, width, height):
    total  = width * height
    packed = bytearray((total + 7) // 8)
    for i, val in enumerate(map_data):
        if val:
            packed[i >> 3] |= (1 << (i & 7))
    return bytes(packed)




packed_map = bitpack_map(MAP_INPUT, MAP_WIDTH, MAP_HEIGHT)
map_bytes  = len(packed_map)

FORMATO = f'<{map_bytes}sBBffffffHH'

num_chunks = TOTAL_RAY_COUNT // RAYS_PER_CHUNK

print(f"Mapa bit-packed           : {map_bytes} bytes  (era {MAP_WIDTH * MAP_HEIGHT} bytes)")
print(f"Total de raios            : {TOTAL_RAY_COUNT}")
print(f"Raios por chunk           : {RAYS_PER_CHUNK}")
print(f"Número de chunks          : {num_chunks}")
print(f"Cenários a executar       : {len(TEST_SCENARIOS)}\n")

ser = serial.Serial(
    port='COM7',
    baudrate=38400,
    timeout=300,
)

time.sleep(2)

for scenario_idx, (name, ox, oy, dx, dy, px, py) in enumerate(TEST_SCENARIOS, start=1):

    print(f"{'='*60}")
    print(f"Cenário {scenario_idx}/{len(TEST_SCENARIOS)}: {name}")
    print(f"  origin=({ox}, {oy})  dir=({dx}, {dy})  plane=({px}, {py})")

    buffer = struct.pack(
        FORMATO,
        packed_map,
        MAP_WIDTH,
        MAP_HEIGHT,
        ox, oy, dx, dy, px, py,
        TOTAL_RAY_COUNT,
        RAYS_PER_CHUNK,
    )

    print(f"  Tamanho do pacote: {len(buffer)} bytes")

    ser.reset_input_buffer()
    ser.write(buffer)
    print("  Pacote enviado. Aguardando respostas...\n")

    all_distances = []
    error_occurred = False

    for chunk_idx in range(num_chunks):
        rays_in_chunk = min(RAYS_PER_CHUNK, TOTAL_RAY_COUNT - chunk_idx * RAYS_PER_CHUNK)
        expected_bytes = rays_in_chunk * 4
        raw = ser.read(expected_bytes)

        if len(raw) != expected_bytes:
            print(f"  [ERRO] Tempo limite na leitura serial! Esperava {expected_bytes} bytes, mas recebeu apenas {len(raw)} bytes.")
            error_occurred = True
            break

        distances = struct.unpack(f'<{rays_in_chunk}f', raw)
        all_distances.extend(distances)

        formatted = " ".join(f"{d:.6f}" for d in distances)
        print(f"  Chunk {chunk_idx + 1:02d}/{num_chunks}: [{formatted}]")

    print(f"\n  Total de distâncias recebidas: {len(all_distances)}")

    EXEC_AMOUNT = 50
    expected_time_bytes = EXEC_AMOUNT * 4
    raw_time = ser.read(expected_time_bytes)
    if len(raw_time) == expected_time_bytes:
        exec_times = struct.unpack(f'<{EXEC_AMOUNT}I', raw_time)
        
        media_us = statistics.mean(exec_times) * 1000.0
        mediana_us = statistics.median(exec_times) * 1000.0
        variancia_us = statistics.variance(exec_times) * 1000000.0 if len(exec_times) > 1 else 0
        desvio_padrao_us = statistics.stdev(exec_times) * 1000.0 if len(exec_times) > 1 else 0
        minimo_us = min(exec_times) * 1000.0
        maximo_us = max(exec_times) * 1000.0
        amplitude_us = maximo_us - minimo_us

        print(f"  Tempos recebidos: {len(exec_times)}")
        print(f"  Média           : {media_us:.3f} us")
        print(f"  Mediana         : {mediana_us:.3f} us")
        print(f"  Desvio Padrão   : {desvio_padrao_us:.3f} us")
        print(f"  Variância       : {variancia_us:.3f} us^2")
        print(f"  Mínimo          : {minimo_us:.0f} us")
        print(f"  Máximo          : {maximo_us:.0f} us")
        print(f"  Amplitude       : {amplitude_us:.0f} us")

        # Salva o array de tempos em um arquivo de log
        time_output_file = f"./times_output_{scenario_idx}.txt"
        with open(time_output_file, "w") as f:
            f.write("\n".join(str(t) for t in exec_times) + "\n")
        print(f"  Tempos salvos em {time_output_file}")
    else:
        print(f"  [AVISO] Falha ao ler os tempos de execução. Recebeu {len(raw_time)} bytes.")

    if not error_occurred:
        output_file = f"./res_output_{scenario_idx}.txt"
        with open(output_file, "w") as f:
            f.write("\n".join(f"{d:.6f}" for d in all_distances) + "\n")
        print(f"  Resultados salvos em {output_file}\n")
    else:
        print(f"  [AVISO] Cenário {scenario_idx} incompleto — arquivo não salvo.\n")


print("="*60)
print("Todos os cenários concluídos.")

ser.close()

